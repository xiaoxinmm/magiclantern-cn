for fname, repls in translations.items():
    path = os.path.join(BASE, fname)
    with open(path, 'r') as f:
        lines = f.readlines()
    
    backup = path + '.bak'
    if not os.path.exists(backup):
        with open(backup, 'w') as f:
            f.writelines(lines)
    
    repls.sort(key=lambda x: x[0], reverse=True)
    changes = 0
    for line_num, new_name in repls:
        idx = line_num - 1
        line = lines[idx]
        new_line = re.sub(r'(\.name\s*=\s*")[^"]*(")', rf'\g<1>{new_name}\g<2>', line)
        if new_line != line:
            lines[idx] = new_line
            changes += 1
    
    with open(path, 'w') as f:
        f.writelines(lines)
    print(f"  {fname}: {changes}/{len(repls)} 条")

