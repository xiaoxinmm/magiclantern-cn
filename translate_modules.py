for fname, repls in translations.items():
    path = os.path.join(BASE, fname)
    if not os.path.exists(path):
        print(f"  ⚠ {fname}: 文件不存在")
        continue
    
    with open(path, 'r') as f:
        lines = f.readlines()
    
    repls.sort(key=lambda x: x[0], reverse=True)
    changes = 0
    for line_num, new_name in repls:
        idx = line_num - 1
        line = lines[idx]
        new_line = re.sub(r'(\.name\s*=\s*")[^"]*(")', rf'\g<1>{new_name}\g<2>', line)
        if new_line != line:
            lines[idx] = new_line
            changes += 1
        else:
            print(f"  ✗ {fname} L{line_num}: {line.strip()[:70]}")
    
    with open(path, 'w') as f:
        f.writelines(lines)
    print(f"  ✓ {fname}: {changes}/{len(repls)} 条")

print("\n模块汉化完成！")
